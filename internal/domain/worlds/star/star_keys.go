func NewDataRegister() (*Register, error) {
	path := paths.AssetsDirectory("stars") + "stars.json"
	r := Register{}
	r.Data = make(map[string][]float64)
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("failed to read star register file: %w", err)
	}
	if err := json.Unmarshal(data, &r); err != nil {
		return nil, fmt.Errorf("failed to unmarshal star register: %w", err)
	}
	return &r, nil
}

